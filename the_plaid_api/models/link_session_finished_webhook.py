from __future__ import annotations

from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel
from .enums.webhook_environment_values import WebhookEnvironmentValuesOrStr


class LinkSessionFinishedWebhook(SdkBaseModel):
    """Contains the state of a completed Link session, along with the public token(s) if available.

    By default, this webhook is sent only for sessions enabled for the Hosted Link flow (including Link Recovery flows),
    a Multi-Item Link flow, or a Layer flow. If you would like to receive this webhook for other sessions, contact your
    account manager or support. This enablement will also enable the ``EVENTS`` webhook for all Link sessions and the
    ability to use ``/link/token/get`` to retrieve events for non-Hosted-Link sessions."""

    webhook_type: str
    """``LINK``"""

    webhook_code: str
    """``SESSION_FINISHED``"""

    status: str
    """The final status of the Link session. Will always be "SUCCESS" or "EXITED"."""

    link_session_id: str
    """The identifier for the Link session."""

    link_token: str
    """The ``link_token`` used to create the Link session."""

    public_token: Optional[str] = UNSET
    """The public token generated by the Link session. This field has been deprecated; please use ``public_tokens``
    instead."""

    public_tokens: Optional[list[str]] = UNSET
    """The public tokens generated by the Link session."""

    user_id: Optional[str] = UNSET
    """The Plaid ``user_id`` of the User associated with this webhook, warning, or error."""

    environment: WebhookEnvironmentValuesOrStr
    """The Plaid environment the webhook was sent from"""


class LinkSessionFinishedWebhookDict(TypedDict):
    webhook_type: str
    webhook_code: str
    status: str
    link_session_id: str
    link_token: str
    public_token: NotRequired[str]
    public_tokens: NotRequired[list[str]]
    user_id: NotRequired[str]
    environment: WebhookEnvironmentValuesOrStr
